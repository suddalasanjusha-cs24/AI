#idfs
import copy

goal_state = [
    [1, 2, 3],
    [4, 5, 6],
    [7, 8, 0]
]

initial_state = [
    [1, 2, 3],
    [4, 0, 5],
    [7, 8, 6]
]


def print_board(matrix):

    for row in matrix:
        print(" ".join(str(x) if x != 0 else "_" for x in row))
    print("-" * 7)

def depth_limited_dfs(current_state, path, current_limit):

    if current_state == goal_state:
        print("Goal reached!")
        print(f"Solution found at depth limit: {len(path) - 1}")
        print("\n--- Solution Path ---")
        for step, state in enumerate(path):
            print(f"Move {step}:")
            print_board(state)
        return True


    if current_limit <= 0:
        return False

    blank_row, blank_col = -1, -1
    for r in range(3):
        for c in range(3):
            if current_state[r][c] == 0:
                blank_row, blank_col = r, c
                break

    possible_moves = []
    directions = [(-1, 0), (1, 0), (0, -1), (0, 1)]
    for dr, dc in directions:
        new_r, new_c = blank_row + dr, blank_col + dc
        if 0 <= new_r < 3 and 0 <= new_c < 3:
            possible_moves.append((new_r, new_c))


    for new_r, new_c in possible_moves:

        new_state = copy.deepcopy(current_state)
        new_state[blank_row][blank_col], new_state[new_r][new_c] = new_state[new_r][new_c], new_state[blank_row][blank_col]

        if new_state not in path:
            path.append(new_state)

            if depth_limited_dfs(new_state, path, current_limit - 1):
                return True

            path.pop()

    return False


def iterative_deepening_search(initial_state):
    print("Initial Board Layout:")
    print_board(initial_state)

    depth = 0
    max_allowable_depth = 50


    while depth <= max_allowable_depth:
        print(f"Searching at depth limit: {depth}...")
        path = [initial_state]


        if depth_limited_dfs(initial_state, path, depth):
            return True

        depth += 1

    print("No solution found within maximum depth limit.")
    return False

iterative_deepening_search(initial_state)